// Convert temperature to natural language description
export const tempToDescription = (tempC: number): string => {
  if (tempC <= -30) return `Extremely cold at ${Math.round(tempC)}°C — bundle up!`;
  if (tempC <= -20) return `Frigid ${Math.round(tempC)}°C — bitter cold`;
  if (tempC <= -10) return `Very cold ${Math.round(tempC)}°C — freezing conditions`;
  if (tempC <= 0) return `Cold ${Math.round(tempC)}°C — near freezing`;
  if (tempC <= 10) return `Chilly ${Math.round(tempC)}°C — grab a jacket`;
  if (tempC <= 18) return `Cool ${Math.round(tempC)}°C — pleasant`;
  if (tempC <= 24) return `Mild ${Math.round(tempC)}°C — comfortable`;
  if (tempC <= 30) return `Warm ${Math.round(tempC)}°C — nice weather`;
  if (tempC <= 35) return `Hot ${Math.round(tempC)}°C — stay hydrated`;
  return `Very hot ${Math.round(tempC)}°C — scorching!`;
};
